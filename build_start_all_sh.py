import os

def generate_shell_script():
    lines = []
    lines.append("#!/bin/bash")
    lines.append("")
    lines.append("# ZO-SENTINEL Startup Script")
    lines.append("# Generated by build_start_all_sh.py")
    lines.append("")
    lines.append("set -e")
    lines.append("")
    lines.append("# Configuration")
    lines.append("export PYTHONPATH=/home/workspace/zo_sentinel:$PYTHONPATH")
    lines.append("cd /home/workspace/zo_sentinel")
    lines.append("")
    lines.append("# Kill any existing instances")
    lines.append("pkill -f 'python.*write_service' || true")
    lines.append("pkill -f 'python.*inference_router' || true")
    lines.append("pkill -f 'supervisord' || true")
    lines.append("")
    lines.append("sleep 2")
    lines.append("")
    lines.append("# Start write_service first (blocks until healthy)")
    lines.append("echo 'Starting write_service...'")
    lines.append("nohup python -m write_service > /var/log/zo_sentinel/write_service.log 2>&1 &")
    lines.append("WRITE_SERVICE_PID=$!")
    lines.append("")
    lines.append("# Wait for write_service to be healthy")
    lines.append("MAX_WAIT=60")
    lines.append("WAIT_COUNT=0")
    lines.append("while [ $WAIT_COUNT -lt $MAX_WAIT ]; do")
    lines.append("    if curl -s -f http://127.0.0.1:8772/health > /dev/null 2>&1; then")
    lines.append("        echo 'write_service is healthy'")
    lines.append("        break")
    lines.append("    fi")
    lines.append("    echo 'Waiting for write_service to be healthy... ($WAIT_COUNT/$MAX_WAIT)'")
    lines.append("    sleep 1")
    lines.append("    WAIT_COUNT=$((WAIT_COUNT + 1))")
    lines.append("done")
    lines.append("")
    lines.append("if [ $WAIT_COUNT -eq $MAX_WAIT ]; then")
    lines.append("    echo 'ERROR: write_service failed to become healthy'")
    lines.append("    exit 1")
    lines.append("fi")
    lines.append("")
    lines.append("# Generate supervisord configuration")
    lines.append("python build_supervisord_conf.py")
    lines.append("")
    lines.append("# Start supervisord")
    lines.append("echo 'Starting supervisord...'")
    lines.append("nohup supervisord -c /home/workspace/zo_sentinel/supervisord.conf > /var/log/zo_sentinel/supervisord.log 2>&1 &")
    lines.append("")
    lines.append("echo 'ZO-SENTINEL startup complete'")
    lines.append("echo 'write_service running on port 8772'")
    lines.append("echo 'inference_router running on port 8773'")
    
    return "\n".join(lines)

if __name__ == "__main__":
    script_content = generate_shell_script()
    output_path = "/home/workspace/zo_sentinel/start_all.sh"
    
    with open(output_path, "w") as f:
        f.write(script_content)
    
    os.chmod(output_path, 0o755)
    print(f"Generated {output_path}")