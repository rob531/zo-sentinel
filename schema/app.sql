-- =====================================================================
-- app.sql  --  ZO SENTINEL APPLICATION SCHEMA  (OWNER: the app)
-- =====================================================================
-- The product's storage: the data served by the 5-endpoint API
-- (ui_server / bulk_assess_api / forensic_detail_api), the user UI, and
-- the admin UI. Workload is OLTP -- concurrent transactional reads/writes,
-- auth, and atomic (decision + audit_log) pairs.
--
-- TARGET ENGINE: DuckDB today (behind write_service :8772) -> Postgres.
-- This is the migration subset. The DDL below is the CURRENT live DuckDB
-- DDL, verbatim, with `-- PORTABILITY:` notes marking each DuckDB-ism and
-- its Postgres equivalent. The app schema is highly portable: native types
-- throughout, only three deltas (uuid default, sequences, caller-side
-- INSERT OR IGNORE).
--
-- All access goes through the write_service bus contract (/write,
-- /execute, /query) -- NEVER a direct duckdb/psycopg import in app code.
-- Source of truth extracted from full_schema_bootstrap.py (Phase A split).
-- =====================================================================

-- ---------------------------------------------------------------------
-- Sequences (app surrogate keys)
-- PORTABILITY: Postgres has native CREATE SEQUENCE; or replace the
-- `BIGINT DEFAULT nextval('seq')` columns with `BIGINT GENERATED BY
-- DEFAULT AS IDENTITY` and drop these.
-- ---------------------------------------------------------------------
CREATE SEQUENCE IF NOT EXISTS seq_signal_id   START 1;
CREATE SEQUENCE IF NOT EXISTS seq_threat_id   START 1;
CREATE SEQUENCE IF NOT EXISTS seq_decision_id START 1;
CREATE SEQUENCE IF NOT EXISTS seq_policy_id   START 1;
CREATE SEQUENCE IF NOT EXISTS seq_defhist_id  START 1;
CREATE SEQUENCE IF NOT EXISTS seq_id          START 1;

-- ---------------------------------------------------------------------
-- Core registry + assessment
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mcp_server_registry (
    server_id         VARCHAR PRIMARY KEY,
    name              VARCHAR,
    registry_source   VARCHAR,
    url               VARCHAR,
    description       TEXT,
    trust_score       FLOAT,
    verdict           VARCHAR,
    verdict_reasoning TEXT,
    confidence        FLOAT,
    last_assessed     TIMESTAMPTZ,
    first_seen        TIMESTAMPTZ,
    last_seen         TIMESTAMPTZ,
    last_scanned      TIMESTAMPTZ,
    scan_count        INTEGER DEFAULT 0,
    risk_tier         VARCHAR,
    metadata          TEXT
);

-- Long-format signal scores. PK(id) + UNIQUE(server_id, signal_name) are
-- REQUIRED for the callers' INSERT ... ON CONFLICT upserts (DuckDB raises
-- a Binder Error without them). See full_schema_bootstrap HISTORY 2026-04-17.
CREATE TABLE IF NOT EXISTS mcp_signal_scores (
    id          BIGINT PRIMARY KEY DEFAULT nextval('seq_signal_id'),
    server_id   VARCHAR NOT NULL,
    signal_name VARCHAR NOT NULL,
    score       FLOAT,
    evidence    TEXT,
    scored_at   TIMESTAMPTZ DEFAULT now(),
    UNIQUE (server_id, signal_name)
);

-- Callers (threat_intel_ingestor, rug_pull_monitor, pi_scorer) MUST set
-- `source` explicitly so UNIQUE(server_id, threat_type, source) dedupes.
CREATE TABLE IF NOT EXISTS mcp_threat_associations (
    id          BIGINT PRIMARY KEY DEFAULT nextval('seq_threat_id'),
    server_id   VARCHAR NOT NULL,
    threat_type VARCHAR NOT NULL,
    severity    VARCHAR,
    evidence    TEXT,
    source      VARCHAR,
    reported_at TIMESTAMPTZ DEFAULT now(),
    UNIQUE (server_id, threat_type, source)
);

CREATE INDEX IF NOT EXISTS idx_signal_scores_server ON mcp_signal_scores(server_id);
CREATE INDEX IF NOT EXISTS idx_signal_scores_name   ON mcp_signal_scores(signal_name);
CREATE INDEX IF NOT EXISTS idx_threats_server       ON mcp_threat_associations(server_id);
CREATE INDEX IF NOT EXISTS idx_threats_severity     ON mcp_threat_associations(severity);

-- Per-server assessment artifacts (served by the forensic API).
