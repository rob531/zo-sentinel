def _age_hours_expression(db: Session):
    """Return a dialect-appropriate age expression measured in hours."""
    try:
        dialect_name = db.get_bind().dialect.name
    except Exception:
        dialect_name = "sqlite"

    if dialect_name == "postgresql":
        return (
            func.extract(
                "epoch",
                func.now() - McpScoreDispute.created_at,
            )
            / 3600.0
        )

    # SQLite is used by the contract harness.  julianday() is also available
    # in SQLite builds that use the standard date functions extension.
    return (
        func.julianday(func.current_timestamp())
        - func.julianday(McpScoreDispute.created_at)
    ) * 24.0


def _fallback_age_hours(created_at: Any) -> float:
    """Calculate age in hours when a database expression cannot be evaluated."""
    if isinstance(created_at, datetime):
        value = created_at
        if value.tzinfo is None:
            value = value.replace(tzinfo=timezone.utc)
        now = datetime.now(timezone.utc)
        return max(0.0, (now - value).total_seconds() / 3600.0)
    return 0.0


def list_disputes_queue(
    db: Session,
    status: Optional[str] = "open",
    limit: Optional[int] = 50,
) -> Dict[str, Any]:
    """List score disputes, newest first by age, with server registry data."""
    if limit is None:
        limit = 50
    limit = max(1, min(int(limit), 200))

    age_expression = _age_hours_expression(db)
    statement = (
        select(
            McpScoreDispute.id,
            McpScoreDispute.server_id,
            McpServerRegistry.name,
            McpServerRegistry.risk_tier,
            McpScoreDispute.proposed_overall_risk,
            McpScoreDispute.reason_category,
            McpScoreDispute.status,
            age_expression.label("age_hours"),
            McpScoreDispute.submitted_by,
            McpScoreDispute.created_at,
        )
        .outerjoin(
            McpServerRegistry,
            McpServerRegistry.server_id == McpScoreDispute.server_id,
        )
    )

    if status is not None and str(status).strip().lower() != "all":
        statement = statement.where(McpScoreDispute.status == status)

    statement = statement.order_by(age_expression.desc()).limit(limit)
    rows = db.execute(statement).all()

    items = []
    for row in rows:
        age = row.age_hours
        try:
            age_hours = float(age)
        except (TypeError, ValueError):
            age_hours = _fallback_age_hours(row.created_at)
        if age_hours < 0:
            age_hours = 0.0

        items.append(
            {
                "id": row.id,
                "server_id": row.server_id,
                "server_name": row.name,
                "current_risk_tier": row.risk_tier,
                "proposed_overall_risk": row.proposed_overall_risk,
                "reason_category": row.reason_category,
                "status": row.status,
                "age_hours": age_hours,
                "submitted_by": row.submitted_by,
            }
        )

    return {"count": len(items), "items": items}


