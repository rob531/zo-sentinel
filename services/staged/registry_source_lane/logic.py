from __future__ import annotations

from typing import Dict, List
from datetime import datetime, timedelta

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.models import McpServerRegistry

def source_lane_counts(db: Session, days: int = 30) -> Dict[str, int]:
    """Count registry entries per source over the last N days."""
    cutoff_date = datetime.now() - timedelta(days=days)
    rows = db.execute(
        select(McpServerRegistry.registry_source, func.count())
        .where(McpServerRegistry.last_seen >= cutoff_date)
        .group_by(McpServerRegistry.registry_source)
    ).all()
    out: Dict[str, int] = {}
    for source, count in rows:
        out[source or "unknown"] = int(count)
    return out

if __name__ == "__main__":
    from fastapi import FastAPI
    from sqlalchemy import create_engine
    from sqlalchemy.orm import sessionmaker
    from sqlalchemy.pool import StaticPool

    app = FastAPI()

    SQLALCHEMY_DATABASE_URL = "sqlite:///:memory:"

    engine = create_engine(
        SQLALCHEMY_DATABASE_URL,
        connect_args={"check_same_thread": False},
        poolclass=StaticPool,
    )

    SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)

    def get_session():
        db = SessionLocal()
        try:
            yield db
        finally:
            db.close()

    app.dependency_overrides[get_session] = get_session

    from app.models import Base
    Base.metadata.create_all(bind=engine)

    db = next(get_session())

    # Seed data
    sources = ["source1", "source2", "source3"]
    for i, source in enumerate(sources):
        for j in range(i + 1):
            db.add(McpServerRegistry(
                server_id=f"server_{i}_{j}",
                registry_source=source,
                last_seen=datetime.now() - timedelta(days=j)
            ))
    db.commit()

    # Test the function
    counts = source_lane_counts(db)
    assert len(counts) == 3
    assert counts["source1"] == 1
    assert counts["source2"] == 2
    assert counts["source3"] == 3

    print("PASS")