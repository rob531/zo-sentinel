-- Immutable audit trail. The admin UI writes here on every mutation
-- (revoke/extend/exempt); a decision and its audit row should be ATOMIC --
-- a transactional guarantee DuckDB's single writer fakes by serialization
-- and Postgres provides natively (the OLTP argument for the migration).
CREATE TABLE IF NOT EXISTS audit_log (
    event_id         VARCHAR PRIMARY KEY DEFAULT gen_random_uuid()::VARCHAR,
    event_type       VARCHAR,
    actor            VARCHAR,
    target_server_id VARCHAR,
    action           VARCHAR,
    outcome          VARCHAR,
    details_json     TEXT,
    immutable        BOOLEAN DEFAULT TRUE,
    timestamp        TIMESTAMPTZ DEFAULT now()
);

-- Analyst-granted exemptions (managed in the admin UI: admin_exemptions.html).
CREATE TABLE IF NOT EXISTS mcp_exemptions (
    exemption_id    VARCHAR PRIMARY KEY DEFAULT gen_random_uuid()::VARCHAR,
    server_id       VARCHAR NOT NULL,
    reason          TEXT,
    granted_by      VARCHAR,
    conditions_json TEXT,
    expires_at      TIMESTAMPTZ,
    active          BOOLEAN DEFAULT TRUE,
    created_at      TIMESTAMPTZ DEFAULT now()
);

