"""logic.py -- the service's data/computation layer (one concern, one file).

Mirrors the exemplar doctrine: import the REAL data layer (app.db/app.models),
never an inline/stub/SQLite-dict model. Pure functions over a Session so the
router stays thin and the contract can exercise this directly.

The set of classes you may import from app.models is FIXED and listed in
docs/SCHEMA_TRUTH.md (generated by tools/emit_schema_truth.py). If the model
you want is not in that file it does not exist -- MCPAxisScores, VulnAdvisories,
app.db.StaticPool and app.dependency_overrides are the four names most often
invented here, and none of them resolve.
"""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Dict, Optional

from fastapi import Depends
from sqlalchemy import create_engine, select
from sqlalchemy.orm import Session, sessionmaker

from app.db import get_session
from app.models import McpScoreDispute


DEFAULT_STATUS = "pending"
MAX_LIMIT = 200


def get_dispute_review_queue(
    db: Session = Depends(get_session),
    status: str = DEFAULT_STATUS,
    limit: int = 50,
) -> Dict[str, Any]:
    """Return score disputes in newest-first order for the requested status."""
    bounded_limit = max(0, min(int(limit), MAX_LIMIT))
    query = select(McpScoreDispute)
    if status is not None:
        query = query.where(McpScoreDispute.status == status)
    query = query.order_by(
        McpScoreDispute.created_at.desc(),
        McpScoreDispute.id.desc(),
    ).limit(bounded_limit)

    rows = db.execute(query).scalars().all()
    disputes = [
        {
            "id": row.id,
            "server_id": row.server_id,
            "submitted_by": row.submitted_by,
            "proposed_overall_risk": row.proposed_overall_risk,
            "reason_category": row.reason_category,
            "status": row.status,
            "explanation": row.explanation,
            "admin_note": row.admin_note,
            "created_at": row.created_at,
            "resolved_at": row.resolved_at,
            "proposed_axes": row.proposed_axes,
        }
        for row in rows
    ]

    return {
        "status": status,
        "count": len(disputes),
        "disputes": disputes,
    }


def get_dispute_queue(
    db: Session = Depends(get_session),
    status: str = DEFAULT_STATUS,
    limit: int = 50,
) -> Dict[str, Any]:
    """Compatibility name for the dispute review queue."""
    return get_dispute_review_queue(db=db, status=status, limit=limit)


def get_disputes(
    db: Session = Depends(get_session),
    status: str = DEFAULT_STATUS,
    limit: int = 50,
) -> Dict[str, Any]:
    """Compatibility name for the dispute review queue."""
    return get_dispute_review_queue(db=db, status=status, limit=limit)


def _self_test() -> None:
    """Exercise the queue against a local in-memory SQLite session."""
    from fastapi import FastAPI

    engine = create_engine("sqlite://")
    McpScoreDispute.__table__.create(engine)
    testing_session = sessionmaker(bind=engine)()

    base = datetime(2024, 1, 1, tzinfo=timezone.utc)
    testing_session.add_all(
        [
            McpScoreDispute(
                server_id=1,
                submitted_by="analyst-a",
                proposed_overall_risk=0.2,
                proposed_axes={"availability": 0.4},
                reason_category="accuracy",
                explanation="Old pending dispute",
                status="pending",
                created_at=base,
            ),
            McpScoreDispute(
                server_id=2,
                submitted_by="analyst-b",
                proposed_overall_risk=0.7,
                proposed_axes={"availability": 0.8},
                reason_category="accuracy",
                explanation="New pending dispute",
                status="pending",
                created_at=base.replace(day=3),
            ),
            McpScoreDispute(
                server_id=3,
                submitted_by="analyst-c",
                proposed_overall_risk=0.9,
                proposed_axes={"availability": 0.9},
                reason_category="accuracy",
                explanation="Resolved dispute",
                status="resolved",
                created_at=base.replace(day=2),
                resolved_at=base.replace(day=4),
            ),
        ]
    )
    testing_session.commit()

    local_app = FastAPI()
    local_app.dependency_overrides[get_session] = lambda: testing_session

    result = get_dispute_review_queue(
        db=testing_session,
        status="pending",
        limit=50,
    )
    assert result["status"] == "pending"
    assert result["count"] == 2
    assert [item["explanation"] for item in result["disputes"]] == [
        "New pending dispute",
        "Old pending dispute",
    ]
    assert result["disputes"][0]["proposed_axes"] == {"availability": 0.8}
    print("PASS")


if __name__ == "__main__":
    _self_test()