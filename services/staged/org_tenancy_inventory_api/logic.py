from __future__ import annotations

from typing import Dict, List

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.models import Org, User, ApiKey

def get_org_tenancy_inventory(db: Session) -> Dict[str, Dict[str, int]]:
    """Retrieve the tenancy inventory for all organizations.

    Returns a dictionary where each key is an organization name and the value
    is another dictionary containing the count of users and active API keys for
    that organization.
    """
    orgs = db.execute(select(Org)).scalars().all()
    inventory: Dict[str, Dict[str, int]] = {}

    for org in orgs:
        user_count = db.execute(
            select(func.count(User.id))
            .where(User.org_id == org.id)
        ).scalar()

        active_api_key_count = db.execute(
            select(func.count(ApiKey.id))
            .where(ApiKey.org_id == org.id)
        ).scalar()

        inventory[org.name] = {
            "user_count": int(user_count),
            "active_api_key_count": int(active_api_key_count)
        }

    return inventory

if __name__ == "__main__":
    from fastapi import FastAPI, Depends
    from app.db import get_session

    app = FastAPI()

    @app.get("/tenancy-inventory")
    def tenancy_inventory(db: Session = Depends(get_session)):
        return get_org_tenancy_inventory(db)

